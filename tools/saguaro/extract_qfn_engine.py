#!/usr/bin/env python3
"""tools/saguaro/extract_qfn_engine.py - writes serve/qfn_engine.py: engines/qfn/serve/server.py's StrataEngine and Vision with
every module-level definition they need (their closure), in the original order and unchanged, so the shared server drives
QFN's engine itself.  Run from the source root after changing engines/qfn's server:  python tools/saguaro/extract_qfn_engine.py"""
import ast
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "engines" / "qfn" / "serve" / "server.py"
OUT = ROOT / "serve" / "qfn_engine.py"
ROOTS = ("StrataEngine", "Vision", "engine_args", "child_env", "configure_batch_telemetry_env", "engine_silence_s",
         "apply_ready_timeout", "effort_end_args", "vision_env")
HEAD = '''"""serve/qfn_engine.py - Qwen3.8-Flash-Next's engine driver (engines/qfn: Strata's batch protocol - BGEN / BDONE / BSTOP,
the server-side slot admission, wrap spill, session files, its vision encoder), taken from engines/qfn/serve/server.py so
the one shared server (serve/server.py --engine qfn) drives it.  GENERATED by tools/saguaro/extract_qfn_engine.py: the
definitions are QFN's own, unchanged - fix them in engines/qfn and extract again."""
from __future__ import annotations

import sys as _sys
from pathlib import Path as _P
_QFN = str(_P(__file__).resolve().parents[1] / "engines" / "qfn")
if _QFN not in _sys.path:
    _sys.path.append(_QFN)   # (strata_control: QFN's own package; appended, so the shared tools/ come first)
'''


def bound(n):
    """Module-level names a statement binds."""
    out = set()
    for x in ast.walk(n):
        if isinstance(x, ast.Name) and isinstance(x.ctx, ast.Store):
            out.add(x.id)
        elif isinstance(x, (ast.FunctionDef, ast.ClassDef)) and x in getattr(n, "body", [n]) or x is n and \
                isinstance(x, (ast.FunctionDef, ast.ClassDef)):
            out.add(x.name)
    if isinstance(n, (ast.FunctionDef, ast.ClassDef)):
        return {n.name}
    if isinstance(n, (ast.Import, ast.ImportFrom)):
        return {(a.asname or a.name).split(".")[0] for a in n.names}
    return out


def main():
    src = SRC.read_text(encoding="utf-8")
    L = src.splitlines()
    t = ast.parse(src)
    by = {}
    for n in t.body:
        for k in bound(n):
            by.setdefault(k, []).append(n)
    loads = lambda n: {x.id for x in ast.walk(n) if isinstance(x, ast.Name) and isinstance(x.ctx, ast.Load)}
    need, todo = set(), list(ROOTS)
    while todo:
        k = todo.pop()
        for n in by.get(k, []):
            if id(n) in need:
                continue
            need.add(id(n))
            todo.extend(x for x in loads(n) if x in by)
    out = [HEAD]
    for n in t.body:
        if id(n) not in need or isinstance(n, ast.ImportFrom) and n.module == "__future__":
            continue
        s = n.lineno - 1
        if getattr(n, "decorator_list", None):
            s = n.decorator_list[0].lineno - 1
        while s > 0 and L[s - 1].startswith("#"):
            s -= 1
        out.append("\n".join(L[s:n.end_lineno]) + ("\n" if isinstance(n, (ast.FunctionDef, ast.ClassDef)) else ""))
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{OUT}: {sum(1 for _ in out) - 1} definitions from {SRC}")


if __name__ == "__main__":
    main()
