class EngineDied(RuntimeError):
    """The engine process ended in the middle of a request (issue #27: on Linux, the out-of-memory killer)."""

class ClientGone(Exception):
    """#1999: the client hung up while its request was being prepared (an image URL downloading, a picture encoding or
    waiting for its turn): nothing is left to answer."""

class QueueWaitExpired(RuntimeError):
    """An inference call waited too long for its first engine turn."""

class EngineSilent(EngineDied):
    """#481: the engine said nothing for too long during a request (or never acknowledged a STOP): the two sides lost
    step - the engine waiting for its next command, the server for this request's end - and the server ended it.  An
    EngineDied, so the request ends with an error and the next one starts the engine again."""

class EngineNonFinite(ValueError):
    """#879: the engine's DONE (or a slot's BDONE) said `nonfinite`: a window's logits held a NaN or an infinity.  The
    engine wrote none of that window's tokens and drops every cached state that may carry the poison, so its next
    request reads the prompt from token 0.  Service.run sends a request that had produced nothing yet once more, and
    ends one that had started (as "length").  A ValueError, so a stream that has started reports it as an error event."""

class EngineOutOfVram(EngineNonFinite):
    """A DONE / BDONE that said `vram`, or an ERR / BRE that says "no VRAM is left": the request's prompt read, batch
    window or context grow found no free VRAM on a card (after the card's expert cache gave what it could).  The engine
    goes on and the slot dropped its state; handled as #879's non-finite end (sent once more when nothing was produced
    yet, a 503 otherwise)."""

class EngineOutOfRam(EngineOutOfVram):
    """A DONE / BDONE that said `ram`, or an ERR / BRE that says "no RAM is left": the conversation's context could not be
    pinned in RAM (KV streaming's host copy) after the engine parked its idle conversations.  Handled as no VRAM: sent
    once more when nothing was produced yet, a 503 otherwise.  The engine goes on, and the conversation keeps what it
    had (a shorter next turn, or fewer long conversations at once, fits)."""

RAM_SHORT = ("no RAM is left to pin the context of this conversation (the engine goes on; it parked every idle "
             "conversation first): fewer long conversations at once, or a shorter one")
VRAM_SHORT = ("no VRAM is left for the context of this conversation (the engine goes on; the card's expert cache gave "
              "all it can first): fewer long conversations at once, or a shorter one")
def engine_refusal(message: str) -> ValueError:
    """The engine's ERR / BRE text as the exception the request ends with: no RAM / no VRAM is the server's (503), not
    the request's.  P124e round 6: a VRAM refusal says "no VRAM is left" and ends as no-VRAM, never as no-RAM.
    P124e round 7: so does "no VRAM for the YaRN RoPE rows" / "no VRAM for its YaRN RoPE rows" (the level switch) -
    it is the same card, the same retry-when-the-cache-settles remedy."""
    if message.startswith("no RAM is left"):
        return EngineOutOfRam(f"{RAM_SHORT} - {message}")
    if message.startswith("no VRAM is left") or message.startswith("no VRAM for"):
        return EngineOutOfVram(f"{VRAM_SHORT} - {message}")
    return ValueError(message)

def raise_bad_finish(finish) -> None:
    """The request's end the engine reported as a failure of its own: #879's non-finite logits, no VRAM, or no RAM."""
    if finish == "nonfinite":
        raise EngineNonFinite("the engine's logits became non-finite (#879)")
    if finish == "vram":
        raise EngineOutOfVram("the GPU had no free memory for this request (the engine goes on); try it again")
    if finish == "ram":
        raise EngineOutOfRam(RAM_SHORT)

class SessionRefused(ValueError):
    """Disk sessions: the engine refused or failed a SAVE / RESTORE and is still in step (`SERR <kind> <published>
    <reason>`).  `kind` is the engine's category - invalid (400), storage (507), memory (503), io (500); `published`:
    a save whose new file already replaced the old one before a later step (the folder flush) failed."""

    STATUS = {"invalid": 400, "storage": 507, "memory": 503, "io": 500}

    def __init__(self, kind: str, message: str, published: bool = False):
        super().__init__(message)
        self.kind = kind if kind in self.STATUS else "io"
        self.published = published

    @property
    def status(self) -> int:
        return self.STATUS[self.kind]

